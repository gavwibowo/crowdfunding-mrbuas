<?php

require_once __DIR__ . '/../koneksi.php';


/*
|--------------------------------------------------------------------------
| Hanya menerima request POST
|--------------------------------------------------------------------------
*/

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {

    header('Location: admin-donor-table.php');
    exit;

}


/*
|--------------------------------------------------------------------------
| Ambil ID donor
|--------------------------------------------------------------------------
*/

$id = (int) ($_POST['id'] ?? 0);


/*
|--------------------------------------------------------------------------
| Validasi ID
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    die('ID donatur tidak valid.');

}


/*
|--------------------------------------------------------------------------
| Query DELETE
|--------------------------------------------------------------------------
*/

$query = "
    DELETE FROM donors
    WHERE id = ?
";


$stmt = mysqli_prepare(
    $koneksi,
    $query
);


mysqli_stmt_bind_param(
    $stmt,
    'i',
    $id
);


/*
|--------------------------------------------------------------------------
| Jalankan DELETE
|--------------------------------------------------------------------------
*/

if (!mysqli_stmt_execute($stmt)) {

    die(
        'Gagal menghapus data donatur: '
        . mysqli_stmt_error($stmt)
    );

}


/*
|--------------------------------------------------------------------------
| Cek apakah data benar-benar ditemukan
|--------------------------------------------------------------------------
*/

if (mysqli_stmt_affected_rows($stmt) === 0) {

    mysqli_stmt_close($stmt);

    die('Data donatur tidak ditemukan.');

}


mysqli_stmt_close($stmt);


/*
|--------------------------------------------------------------------------
| Kembali ke tabel donor
|--------------------------------------------------------------------------
*/

header(
    'Location: admin-donor-table.php'
);

exit;